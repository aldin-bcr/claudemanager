'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  list: () => ipcRenderer.invoke('sessions:list'),
  openTranscript: (id) => ipcRenderer.invoke('transcript:open', id),
  closeTranscript: () => ipcRenderer.invoke('transcript:close'),
  agentSend: (id, text, opts) => ipcRenderer.invoke('agent:send', id, text, opts),
  agentStop: (id) => ipcRenderer.invoke('agent:stop', id),
  managerSend: (text, opts) => ipcRenderer.invoke('manager:send', text, opts),
  managerStart: () => ipcRenderer.invoke('manager:start'),
  managerStop: () => ipcRenderer.invoke('manager:stop'),
  managerRestart: () => ipcRenderer.invoke('manager:restart'),
  setSettings: (settings) => ipcRenderer.invoke('settings:set', settings),
  chooseDir: (defaultPath) => ipcRenderer.invoke('dialog:chooseDir', defaultPath),
  createTeamSession: (spec) => ipcRenderer.invoke('team:create', spec),
  adoptSession: (opts) => ipcRenderer.invoke('team:adopt', opts),
  leaveTeam: (id) => ipcRenderer.invoke('team:leave', id),
  saveTemplate: (name, role) => ipcRenderer.invoke('team:saveTemplate', name, role),
  deleteTemplate: (name) => ipcRenderer.invoke('team:deleteTemplate', name),
  sendReply: (opts) => ipcRenderer.invoke('reply:send', opts),
  stopReply: (id) => ipcRenderer.invoke('reply:stop', id),
  rulesGet: () => ipcRenderer.invoke('rules:get'),
  rulesSave: (r) => ipcRenderer.invoke('rules:save', r),
  rulesDelete: (id) => ipcRenderer.invoke('rules:delete', id),
  rulesMove: (id, dir) => ipcRenderer.invoke('rules:move', id, dir),
  rulesToggle: (id, on) => ipcRenderer.invoke('rules:toggle', id, on),
  rulesPause: (p) => ipcRenderer.invoke('rules:pause', p),
  rulesSimulate: (ev) => ipcRenderer.invoke('rules:simulate', ev),
  onRulesChanged: (cb) => ipcRenderer.on('rules:changed', () => cb()),
  tickGet: () => ipcRenderer.invoke('tick:get'),
  tickNow: () => ipcRenderer.invoke('tick:now'),
  onTickChanged: (cb) => ipcRenderer.on('tick:changed', () => cb()),
  queueGet: () => ipcRenderer.invoke('queue:get'),
  queueRemove: (id, q) => ipcRenderer.invoke('queue:remove', id, q),
  queueMove: (id, q, d) => ipcRenderer.invoke('queue:move', id, q, d),
  queueUrgent: (id, q) => ipcRenderer.invoke('queue:urgent', id, q),
  queueSendNow: (id, q) => ipcRenderer.invoke('queue:sendNow', id, q),
  onQueueChanged: (cb) => ipcRenderer.on('queue:changed', (_e, q) => cb(q)),
  permGet: () => ipcRenderer.invoke('perm:get'),
  permDecide: (aid, d) => ipcRenderer.invoke('perm:decide', aid, d),
  permRevoke: (gid) => ipcRenderer.invoke('perm:revoke', gid),
  onPermChanged: (cb) => ipcRenderer.on('perm:changed', () => cb()),
  optionSet: (id, flag, on, value) => ipcRenderer.invoke('option:set', id, flag, on, value),
  agentRestart: (id, when) => ipcRenderer.invoke('agent:restart', id, when),
  cliOptions: (id) => ipcRenderer.invoke('cli:options', id),
  setEffort: (id, level) => ipcRenderer.invoke('session:setEffort', id, level),
  renameSession: (id, name) => ipcRenderer.invoke('session:rename', id, name),
  setColor: (id, color) => ipcRenderer.invoke('meta:setColor', id, color),
  deleteSession: (id) => ipcRenderer.invoke('session:delete', id),
  onLive: (cb) => ipcRenderer.on('live:update', (_e, live) => cb(live)),
  onAppend: (cb) => ipcRenderer.on('transcript:append', (_e, payload) => cb(payload)),
  onAgentsState: (cb) => ipcRenderer.on('agents:state', (_e, p) => cb(p)),
  onManagerState: (cb) => ipcRenderer.on('manager:state', (_e, p) => cb(p)),
  onTeamEvent: (cb) => ipcRenderer.on('team:event', (_e, p) => cb(p)),
  onReplyState: (cb) => ipcRenderer.on('reply:state', (_e, p) => cb(p)),
  onReplyDone: (cb) => ipcRenderer.on('reply:done', (_e, p) => cb(p)),
});
